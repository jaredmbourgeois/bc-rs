//! The generated tree is the generator's own and nothing else's: `--check`
//! names every difference, a regeneration removes what it no longer produces,
//! and a file no run produced stops the run before anything is written. What
//! tells the generator its own files from anyone else's is the manifest, so a
//! manifest it cannot read — or one that claims a file outside its own
//! directories — stops the run too.

use crate::support::{Scratch, assert_answer, assert_findings, run_in};

const MANIFEST: &str = "generated/telemetry/manifest.json";
const MANIFEST_CHANGED: &str = "error[output-changed]: `generated/telemetry/manifest.json` differs \
                                from what the definitions generate";
const FRESH: &str = "generated/telemetry: fresh (1 file)\n";

#[test]
fn check_names_a_changed_and_a_missing_file() {
    let scratch = Scratch::of_the_canonical_vocabulary();
    scratch.edit(MANIFEST, "\"Checkout health\"", "\"Edited by hand\"");
    assert_findings(&run_in(scratch.path(), &["--check"]), &[MANIFEST_CHANGED]);

    scratch.remove(MANIFEST);
    assert_findings(
        &run_in(scratch.path(), &["--check"]),
        &["error[output-missing]: `generated/telemetry/manifest.json` is generated but missing"],
    );
}

#[test]
fn a_file_no_run_produced_is_refused_and_nothing_is_written() {
    let scratch = Scratch::of_the_canonical_vocabulary();
    scratch.write("generated/telemetry/notes.md", "hand-written\n");
    // A module's own generated directory is the generator's as the root's is.
    scratch.write(
        "services/payments/generated/telemetry/rust/extra.rs",
        "// hand-written\n",
    );
    assert_findings(
        &run_in(scratch.path(), &["--check"]),
        &[
            "error[output-unexpected]: `generated/telemetry/notes.md` is in a directory the \
             generator owns, and no run generated it",
            "error[output-unexpected]: `services/payments/generated/telemetry/rust/extra.rs` is \
             in a directory the generator owns, and no run generated it",
        ],
    );

    scratch.edit(MANIFEST, "\"Checkout health\"", "\"Stale\"");
    assert_findings(
        &run_in(scratch.path(), &[]),
        &[
            "error[output-unexpected]: `generated/telemetry/notes.md` is in a directory the \
             generator owns, and no run generated it; nothing was written — move it out, or \
             choose another `output`",
            "error[output-unexpected]: `services/payments/generated/telemetry/rust/extra.rs` is \
             in a directory the generator owns, and no run generated it; nothing was written — \
             move it out, or choose another `output`",
        ],
    );
    assert!(
        scratch.read(MANIFEST).contains("\"Stale\""),
        "a refused run wrote the manifest anyway"
    );
}

/// A file the previous manifest lists, and this run does not produce, was the
/// generator's: a regeneration removes it, and the directory it leaves empty —
/// in the root's output directory and in a module's alike.
#[test]
fn a_file_an_earlier_run_generated_is_stale_and_a_regeneration_removes_it() {
    let scratch = Scratch::of_the_canonical_vocabulary();
    scratch.edit(
        MANIFEST,
        "\"files\": []",
        "\"files\": [\n    \"generated/telemetry/old/notes.txt\",\n    \
         \"services/payments/generated/telemetry/rust/old.rs\"\n  ]",
    );
    scratch.write("generated/telemetry/old/notes.txt", "from an earlier run\n");
    scratch.write(
        "services/payments/generated/telemetry/rust/old.rs",
        "// from an earlier run\n",
    );
    assert_findings(
        &run_in(scratch.path(), &["--check"]),
        &[
            MANIFEST_CHANGED,
            "error[output-stale]: `generated/telemetry/old/notes.txt` was generated by an earlier \
             run and is no longer produced",
            "error[output-stale]: `services/payments/generated/telemetry/rust/old.rs` was \
             generated by an earlier run and is no longer produced",
        ],
    );

    assert_answer(
        &run_in(scratch.path(), &[]),
        "generated/telemetry: wrote 1, removed 2, unchanged 0\n",
    );
    assert!(
        !scratch.exists("generated/telemetry/old"),
        "the emptied directory remains"
    );
    assert!(
        !scratch.exists("services/payments/generated/telemetry/rust"),
        "the emptied directory remains"
    );
    // The directory the generator owns is never pruned, emptied or not.
    assert!(scratch.exists("services/payments/generated/telemetry"));
    assert_answer(&run_in(scratch.path(), &["--check"]), FRESH);
}

/// Removing one stale file prunes its directory only once nothing is left in it.
#[test]
fn a_directory_still_holding_a_stale_file_is_kept_until_it_is_empty() {
    let scratch = Scratch::of_the_canonical_vocabulary();
    scratch.edit(
        MANIFEST,
        "\"files\": []",
        "\"files\": [\n    \"generated/telemetry/old/a.txt\",\n    \
         \"generated/telemetry/old/b.txt\"\n  ]",
    );
    scratch.write("generated/telemetry/old/a.txt", "from an earlier run\n");
    scratch.write("generated/telemetry/old/b.txt", "from an earlier run\n");
    assert_answer(
        &run_in(scratch.path(), &[]),
        "generated/telemetry: wrote 1, removed 2, unchanged 0\n",
    );
    assert!(!scratch.exists("generated/telemetry/old"));
}

/// A module that left the tree leaves its generated files where they were; the
/// manifest still says where, so the run that retires it removes them.
#[test]
fn a_retired_modules_generated_files_are_removed_with_it() {
    let scratch = Scratch::of_the_canonical_vocabulary();
    scratch.edit(
        MANIFEST,
        "\"files\": []",
        "\"files\": [\n    \"services/payments/ledger/generated/telemetry/rust/ledger.rs\"\n  ]",
    );
    scratch.write(
        "services/payments/ledger/generated/telemetry/rust/ledger.rs",
        "// from an earlier run\n",
    );
    scratch.remove("services/payments/ledger/bc-telemetry.json");
    scratch.edit(
        "bc-telemetry.toml",
        "[generate]",
        "[retired]\nmodules = [\"ledger\"]\n\n[generate]",
    );
    assert_answer(
        &run_in(scratch.path(), &[]),
        "generated/telemetry: wrote 1, removed 1, unchanged 0\n",
    );
    assert!(!scratch.exists("services/payments/ledger/generated/telemetry/rust"));
    assert_answer(&run_in(scratch.path(), &["--check"]), FRESH);
}

/// `output` may change: the manifest is moved to where the new path puts it,
/// and the next run removes the rest from where the old path put it.
#[test]
fn an_output_that_changes_takes_its_files_with_it_once_the_manifest_is_moved() {
    let scratch = Scratch::of_the_canonical_vocabulary();
    scratch.edit(
        MANIFEST,
        "\"files\": []",
        "\"files\": [\n    \"generated/telemetry/postgresql/layout.sql\"\n  ]",
    );
    scratch.write(
        "generated/telemetry/postgresql/layout.sql",
        "-- from an earlier run\n",
    );
    scratch.edit(
        "bc-telemetry.toml",
        "output = \"generated/telemetry\"",
        "output = \"build/telemetry\"",
    );
    scratch.rename(MANIFEST, "build/telemetry/manifest.json");
    assert_answer(
        &run_in(scratch.path(), &[]),
        "build/telemetry: wrote 1, removed 1, unchanged 0\n",
    );
    assert!(!scratch.exists("generated/telemetry/postgresql"));
    assert_answer(
        &run_in(scratch.path(), &["--check"]),
        "build/telemetry: fresh (1 file)\n",
    );
}

